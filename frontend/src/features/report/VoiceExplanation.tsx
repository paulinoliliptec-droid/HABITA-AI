"use client";

import { useEffect, useRef, useState } from "react";
import { Button } from "@/components/ui/Button";
import type { MatterCapability } from "@/features/permit/capability";
import { useI18n } from "@/i18n/useI18n";
import { getVoiceLine, getVoiceScript } from "./api";
import type { PermitReport, VoiceScript } from "./types";
import { RemoteSynth } from "./voiceAudio";
import { VoicePlayer, voiceNotes, type SynthLike, type VoiceState } from "./voicePlayer";
import styles from "./VoiceExplanation.module.css";

type Numbered = SpeechSynthesisUtterance & { index: number };
type BrowserPlayer = VoicePlayer<SpeechSynthesisVoice, Numbered>;
type Remote = RemoteSynth<SpeechSynthesisVoice, Numbered>;

const browserSynth = (): SynthLike<SpeechSynthesisVoice, Numbered> | null =>
  typeof window !== "undefined" && "speechSynthesis" in window ? window.speechSynthesis : null;

/** HR-007: listen to the report, with the sentence being said on screen. */
export function VoiceExplanation({ report, own }: { report: PermitReport; own: MatterCapability | null }) {
  const { lang, t } = useI18n();
  const propertyId = report.property.property_id;
  const player = useRef<BrowserPlayer | null>(null);
  const remote = useRef<Remote | null>(null);
  const [script, setScript] = useState<VoiceScript | null>(null);
  const [state, setState] = useState<VoiceState>("idle");
  const [line, setLine] = useState<string | null>(null);
  const [fellBack, setFellBack] = useState(false);

  // A report or language that changed is never read on from the old one.
  useEffect(() => {
    const controller = new AbortController();
    getVoiceScript(propertyId, own, lang, controller.signal).then(setScript, () => {});
    return () => {
      controller.abort();
      player.current?.stop();
      remote.current?.dispose();
      player.current = remote.current = null;
      setScript(null);
      setFellBack(false);
    };
  }, [report, own, lang, propertyId]);

  const browser = browserSynth();
  const usingServer = script?.audio === true && !fellBack;
  if (!browser && script && !script.audio) {
    return <p className={styles.note}>{t("This browser cannot read the report aloud.")}</p>;
  }

  function listen() {
    if (!script) return;
    let synth = browser;
    remote.current?.dispose();
    remote.current = null;
    if (script.audio && !fellBack) {
      const load = async (index: number) => URL.createObjectURL(await getVoiceLine(propertyId, own, lang, script.version, index));
      remote.current = new RemoteSynth(load, script.lines.length, new Audio(), browser, () => setFellBack(true), URL.revokeObjectURL);
      synth = remote.current;
    }
    if (!synth) return;
    player.current = new VoicePlayer(
      synth,
      (text, index) =>
        Object.assign(browser ? new SpeechSynthesisUtterance(text) : { lang: "", voice: null, rate: 1, onend: null, onerror: null }, { index }) as Numbered,
      (next, sentence) => {
        setState(next);
        setLine(sentence);
      },
    );
    player.current.play(script.lines, lang);
  }

  // Asked on every render: some browsers load their voices late.
  const { noVoice, mayLeaveDevice } = voiceNotes(browser?.getVoices() ?? [], lang);

  return (
    <div className={styles.voice}>
      <div className={styles.controls}>
        {(state === "idle" || state === "failed") && (
          <Button variant="secondary" onClick={listen} disabled={!script}>
            {t("Listen")}
          </Button>
        )}
        {state === "playing" && (
          <Button variant="secondary" onClick={() => player.current?.pause()}>
            {t("Pause")}
          </Button>
        )}
        {state === "paused" && (
          <Button variant="secondary" onClick={() => player.current?.resume()}>
            {t("Resume")}
          </Button>
        )}
        {(state === "playing" || state === "paused") && (
          <>
            <Button variant="secondary" onClick={() => player.current?.repeat()}>
              {t("Repeat")}
            </Button>
            <Button variant="ghost" onClick={() => player.current?.stop()}>
              {t("Stop")}
            </Button>
          </>
        )}
      </div>
      {line && <p className={styles.line}>{line}</p>}
      {state === "failed" && <p className={styles.note}>{t("The audio stopped. The written report is unaffected.")}</p>}
      {usingServer && <p className={styles.note}>{t("The audio is generated by ElevenLabs from the report's text.")}</p>}
      {!usingServer && noVoice && state !== "idle" && <p className={styles.note}>{t("This device has no voice for this language; the accent may be wrong.")}</p>}
      {!usingServer && mayLeaveDevice && <p className={styles.note}>{t("This browser's voice may send the text to its provider.")}</p>}
    </div>
  );
}
