"use client";

import { useEffect, useId, useState } from "react";
import { Button } from "@/components/ui/Button";
import { reportChanged } from "@/features/report/api";
import { useI18n } from "@/i18n/useI18n";
import { ApiError } from "@/lib/api";
import {
  conceptImage,
  conceptOptions,
  createConcept,
  deleteConcept,
  fileContent,
  listConcepts,
  listFiles,
  type Concept,
  type MatterFile,
} from "./api";
import { ImageViewer } from "./ImageViewer";
import styles from "./Permit.module.css";

const isPlan = (f: MatterFile) => f.kind === "plan" || f.is_plan === true;
const NOTICE = "Concept generated by AI — not a project, not an authorisation, not a promise of cost";
const PLAN_NOTICE = "A view from a plan may not match your plan exactly.";

/** HR-012: before/after concepts from the user's own photos. Illustrations only; they change nothing in the assessment. */
export function PermitConcepts({ matterId, token, filesVersion }: { matterId: string; token: string; filesVersion: number }) {
  const { t } = useI18n();
  const id = useId();
  const [photos, setPhotos] = useState<MatterFile[]>([]);
  const [oldPhotos, setOldPhotos] = useState(0);
  const [large, setLarge] = useState<{ src: string; alt: string; caption?: string } | null>(null);
  const [options, setOptions] = useState<{ key: string; label: string; source: "photo" | "plan" }[]>([]);
  const [byId, setById] = useState<Record<string, MatterFile>>({});
  const [concepts, setConcepts] = useState<Concept[]>([]);
  const [fileId, setFileId] = useState("");
  const [change, setChange] = useState("");
  const [images, setImages] = useState<Record<string, string>>({});
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    let cancelled = false;
    Promise.all([listFiles(matterId, token), conceptOptions(matterId, token), listConcepts(matterId, token)])
      .then(([files, opts, list]) => {
        if (cancelled) return;
        // A photo (checked: not a plan) or a plan (chosen as one, or recognised by the reader), with no people seen.
        const usable = (f: MatterFile) =>
          f.people_visible === false && ((f.kind === "photo" && f.is_plan === false && f.content_type !== "application/pdf") || isPlan(f));
        setPhotos(files.filter(usable));
        setById(Object.fromEntries(files.map((f) => [f.file_id, f])));
        // Read before HABITA checked for people and plans: they need adding again to be used here.
        setOldPhotos(files.filter((f) => !usable(f) && f.read_status === "read" && (f.people_visible === null || f.is_plan === null)).length);
        // A deleted file can't stay chosen, and nothing deleted stays open large.
        setFileId((id) => (files.some((f) => f.file_id === id && usable(f)) ? id : ""));
        setLarge(null);
        setOptions(opts);
        setConcepts(list);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [matterId, token, attempt, filesVersion]); // the files panel tells this one when a photo is added or deleted

  // Each concept is shown beside its original; both are fetched with the matter's token and shown from blobs.
  useEffect(() => {
    let cancelled = false;
    // A PDF plan can't be shown as a picture, so only its concept is fetched.
    const wanted = concepts
      .flatMap((c) => [`c:${c.concept_id}`, ...(byId[c.file_id]?.content_type === "application/pdf" ? [] : [`f:${c.file_id}`])])
      .filter((k) => !images[k]);
    Promise.all(
      wanted.map(async (k) => {
        const blob = k.startsWith("c:")
          ? await conceptImage(matterId, token, k.slice(2))
          : await fileContent(matterId, token, k.slice(2));
        return [k, URL.createObjectURL(blob)] as const;
      }),
    )
      .then((pairs) => !cancelled && pairs.length && setImages((m) => ({ ...m, ...Object.fromEntries(pairs) })))
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [concepts, images, matterId, token, byId]);

  async function make() {
    setBusy(true);
    setError(null);
    try {
      const made = await createConcept(matterId, token, fileId, change);
      setConcepts((list) => [...list, made]);
      reportChanged();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t("Something went wrong. Please try again."));
    } finally {
      setBusy(false);
    }
  }

  async function remove(conceptId: string) {
    try {
      await deleteConcept(matterId, token, conceptId);
      setConcepts((list) => list.filter((c) => c.concept_id !== conceptId));
      setLarge(null);
      reportChanged();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t("Something went wrong. Please try again."));
    }
  }

  if (!options.length) return null; // this type of request has no concepts
  return (
    <div className={styles.files}>
      <h3 className={styles.filesTitle}>{t("Before / after concepts")}</h3>
      <p className={styles.filesPurpose}>
        {t("See an idea of the change on one of your photos, or a 3D view and a realistic image from your plan. It is only an illustration: not a project, not an authorisation and not a promise of cost.")}
      </p>
      {photos.length === 0 ? (
        <p className={styles.fieldHint}>
          {t("Add a photo of a room, or a plan, above first. HABITA uses only files it has checked and found no people in.")}{" "}
          <Button variant="ghost" onClick={() => setAttempt((n) => n + 1)}>
            {t("Refresh")}
          </Button>
        </p>
      ) : (
        <div className={styles.affordForm}>
          <div className={styles.affordField}>
            <label className={styles.fieldLabel} htmlFor={`${id}-photo`}>
              {t("Photo")}
            </label>
            <select
              id={`${id}-photo`}
              value={fileId}
              onChange={(e) => {
                setFileId(e.target.value);
                setChange(""); // the choices differ between a photo and a plan
              }}
            >
              <option value="">{t("Choose a photo")}</option>
              {photos.map((p, n) => (
                <option key={p.file_id} value={p.file_id}>
                  {isPlan(p) ? t("Plan") : t("Photo")} {n + 1} · {new Date(p.added_at).toLocaleDateString()}
                </option>
              ))}
            </select>
          </div>
          <div className={styles.affordField}>
            <label className={styles.fieldLabel} htmlFor={`${id}-change`}>
              {t("Change to show")}
            </label>
            <select id={`${id}-change`} value={change} onChange={(e) => setChange(e.target.value)}>
              <option value="">{t("Choose a change")}</option>
              {options.filter((o) => o.source === (byId[fileId] && isPlan(byId[fileId]) ? "plan" : "photo")).map((o) => (
                <option key={o.key} value={o.key}>
                  {t(o.label)}
                </option>
              ))}
            </select>
          </div>
          <Button variant="primary" size="lg" onClick={() => void make()} disabled={busy || !fileId || !change}>
            {busy ? t("Generating… this can take a minute") : t("Show the concept")}
          </Button>
        </div>
      )}
      {oldPhotos > 0 && (
        <p className={styles.fieldHint}>
          {t("Files added before HABITA checked them for people and plans can't be used here: add them again, choosing Plan for a plan.")}
        </p>
      )}
      <p className={styles.fieldHint}>{t("At most 3 concepts from photos and 3 from plans per matter.")}</p>
      {error && (
        <p className={styles.error} role="alert">
          {error}
        </p>
      )}
      {concepts.map((c) => (
        <figure key={c.concept_id} className={styles.concept}>
          <div className={styles.conceptPair}>
            <div>
              <p className={styles.fieldHint}>{byId[c.file_id] && isPlan(byId[c.file_id]) ? t("Before: your plan") : t("Before: your photo")}</p>
              {images[`f:${c.file_id}`] && (
                <button type="button" className={styles.thumb} onClick={() => setLarge({ src: images[`f:${c.file_id}`], alt: t("Your photo") })}>
                  {/* eslint-disable-next-line @next/next/no-img-element -- a private blob, not an optimisable URL */}
                  <img src={images[`f:${c.file_id}`]} alt={t("Your photo")} />
                </button>
              )}
            </div>
            <div>
              <p className={styles.fieldHint}>{t("After: concept")}</p>
              {images[`c:${c.concept_id}`] && (
                <button
                  type="button"
                  className={styles.thumb}
                  onClick={() => setLarge({ src: images[`c:${c.concept_id}`], alt: t(c.change_label), caption: byId[c.file_id] && isPlan(byId[c.file_id]) ? `${t(NOTICE)} ${t(PLAN_NOTICE)}` : t(NOTICE) })}
                >
                  {/* eslint-disable-next-line @next/next/no-img-element -- a private blob, not an optimisable URL */}
                  <img src={images[`c:${c.concept_id}`]} alt={t(c.change_label)} />
                </button>
              )}
            </div>
          </div>
          <figcaption className={styles.fieldHint}>
            <strong>{t(c.change_label)}</strong> · {new Date(c.created_at).toLocaleDateString()} · {t(NOTICE)}
            {byId[c.file_id] && isPlan(byId[c.file_id]) && <> {t(PLAN_NOTICE)}</>}
          </figcaption>
          <Button variant="ghost" onClick={() => void remove(c.concept_id)}>
            {t("Delete")}
          </Button>
        </figure>
      ))}
      {concepts.length > 0 && <p className={styles.fieldHint}>{t("Click a picture to see it large.")}</p>}
      {large && <ImageViewer src={large.src} alt={large.alt} caption={large.caption} onClose={() => setLarge(null)} />}
    </div>
  );
}
