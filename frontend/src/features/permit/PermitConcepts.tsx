"use client";

import { useEffect, useId, useState } from "react";
import { Button } from "@/components/ui/Button";
import { reportChanged } from "@/features/report/api";
import { useI18n } from "@/i18n/useI18n";
import { ApiError } from "@/lib/api";
import {
  conceptImage,
  conceptOptions,
  createConcept,
  deleteConcept,
  fileContent,
  listConcepts,
  listFiles,
  type Concept,
  type MatterFile,
} from "./api";
import styles from "./Permit.module.css";

const NOTICE = "Concept generated by AI — not a project, not an authorisation, not a promise of cost";

/** HR-012: before/after concepts from the user's own photos. Illustrations only; they change nothing in the assessment. */
export function PermitConcepts({ matterId, token }: { matterId: string; token: string }) {
  const { t } = useI18n();
  const id = useId();
  const [photos, setPhotos] = useState<MatterFile[]>([]);
  const [options, setOptions] = useState<{ key: string; label: string }[]>([]);
  const [concepts, setConcepts] = useState<Concept[]>([]);
  const [fileId, setFileId] = useState("");
  const [change, setChange] = useState("");
  const [images, setImages] = useState<Record<string, string>>({});
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    let cancelled = false;
    Promise.all([listFiles(matterId, token), conceptOptions(matterId, token), listConcepts(matterId, token)])
      .then(([files, opts, list]) => {
        if (cancelled) return;
        setPhotos(files.filter((f) => f.kind === "photo" && f.content_type !== "application/pdf" && f.people_visible === false));
        setOptions(opts);
        setConcepts(list);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [matterId, token, attempt]);

  // Each concept is shown beside its original; both are fetched with the matter's token and shown from blobs.
  useEffect(() => {
    let cancelled = false;
    const wanted = concepts.flatMap((c) => [`c:${c.concept_id}`, `f:${c.file_id}`]).filter((k) => !images[k]);
    Promise.all(
      wanted.map(async (k) => {
        const blob = k.startsWith("c:")
          ? await conceptImage(matterId, token, k.slice(2))
          : await fileContent(matterId, token, k.slice(2));
        return [k, URL.createObjectURL(blob)] as const;
      }),
    )
      .then((pairs) => !cancelled && pairs.length && setImages((m) => ({ ...m, ...Object.fromEntries(pairs) })))
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [concepts, images, matterId, token]);

  async function make() {
    setBusy(true);
    setError(null);
    try {
      const made = await createConcept(matterId, token, fileId, change);
      setConcepts((list) => [...list, made]);
      reportChanged();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t("Something went wrong. Please try again."));
    } finally {
      setBusy(false);
    }
  }

  async function remove(conceptId: string) {
    try {
      await deleteConcept(matterId, token, conceptId);
      setConcepts((list) => list.filter((c) => c.concept_id !== conceptId));
      reportChanged();
    } catch (err) {
      setError(err instanceof ApiError ? err.message : t("Something went wrong. Please try again."));
    }
  }

  if (!options.length) return null; // this type of request has no concepts
  return (
    <div className={styles.files}>
      <h3 className={styles.filesTitle}>{t("Before / after concepts")}</h3>
      <p className={styles.filesPurpose}>
        {t("See an idea of the change on one of your photos. It is only an illustration: not a project, not an authorisation and not a promise of cost.")}
      </p>
      {photos.length === 0 ? (
        <p className={styles.fieldHint}>
          {t("Add a photo of the room above first. HABITA uses only photos it has checked and found no people in.")}{" "}
          <Button variant="ghost" onClick={() => setAttempt((n) => n + 1)}>
            {t("Refresh")}
          </Button>
        </p>
      ) : (
        <div className={styles.affordForm}>
          <div className={styles.affordField}>
            <label className={styles.fieldLabel} htmlFor={`${id}-photo`}>
              {t("Photo")}
            </label>
            <select id={`${id}-photo`} value={fileId} onChange={(e) => setFileId(e.target.value)}>
              <option value="">{t("Choose a photo")}</option>
              {photos.map((p, n) => (
                <option key={p.file_id} value={p.file_id}>
                  {t("Photo")} {n + 1} · {new Date(p.added_at).toLocaleDateString()}
                </option>
              ))}
            </select>
          </div>
          <div className={styles.affordField}>
            <label className={styles.fieldLabel} htmlFor={`${id}-change`}>
              {t("Change to show")}
            </label>
            <select id={`${id}-change`} value={change} onChange={(e) => setChange(e.target.value)}>
              <option value="">{t("Choose a change")}</option>
              {options.map((o) => (
                <option key={o.key} value={o.key}>
                  {t(o.label)}
                </option>
              ))}
            </select>
          </div>
          <Button onClick={() => void make()} disabled={busy || !fileId || !change}>
            {busy ? t("Generating… this can take a minute") : t("Show the concept")}
          </Button>
        </div>
      )}
      <p className={styles.fieldHint}>{t("At most 3 concepts per matter.")}</p>
      {error && (
        <p className={styles.error} role="alert">
          {error}
        </p>
      )}
      {concepts.map((c) => (
        <figure key={c.concept_id} className={styles.concept}>
          <div className={styles.conceptPair}>
            <div>
              <p className={styles.fieldHint}>{t("Before: your photo")}</p>
              {/* eslint-disable-next-line @next/next/no-img-element -- a private blob, not an optimisable URL */}
              {images[`f:${c.file_id}`] && <img src={images[`f:${c.file_id}`]} alt={t("Your photo")} />}
            </div>
            <div>
              <p className={styles.fieldHint}>{t("After: concept")}</p>
              {/* eslint-disable-next-line @next/next/no-img-element -- a private blob, not an optimisable URL */}
              {images[`c:${c.concept_id}`] && <img src={images[`c:${c.concept_id}`]} alt={t(c.change_label)} />}
            </div>
          </div>
          <figcaption className={styles.fieldHint}>
            <strong>{t(c.change_label)}</strong> · {new Date(c.created_at).toLocaleDateString()} · {t(NOTICE)}
          </figcaption>
          <Button variant="ghost" onClick={() => void remove(c.concept_id)}>
            {t("Delete")}
          </Button>
        </figure>
      ))}
    </div>
  );
}
