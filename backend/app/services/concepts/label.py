"""HR-012: the notice burned into every concept, in both languages (AC12.3)."""

import io

from PIL import Image, ImageDraw, ImageFont

from app.services.i18n.translator import msg

NOTICE_EN = msg("Concept generated by AI — not a project, not an authorisation, not a promise of cost")
NOTICE_PT = "Conceito gerado por IA — não é um projeto, não é uma autorização, não é uma promessa de custo"
#: Pinned beside catalog.PLAN_NOTICE_EN, added to a view made from a plan.
PLAN_NOTICE_PT = "Pode não corresponder exatamente à sua planta"
MAX_SIDE = 1600
#: DejaVu covers "ã", "é" and "—"; the backend image installs it (fonts-dejavu-core).
FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"


EDIT_SIDE = 1536


def for_editing(image_bytes: bytes) -> bytes:
    """The photo as the image service gets it: a JPEG no larger than ``EDIT_SIDE`` on its long side."""
    with Image.open(io.BytesIO(image_bytes)) as source:
        if source.width * source.height > 40_000_000:
            raise ValueError("image too large")
        image = source.convert("RGB")
    image.thumbnail((EDIT_SIDE, EDIT_SIDE))
    out = io.BytesIO()
    image.save(out, "JPEG", quality=90)
    return out.getvalue()


def _wrap(text: str, font, width: int) -> list[str]:
    """Whole words per line, so no part of the notice is ever clipped."""
    lines, current = [], ""
    for word in text.split():
        candidate = f"{current} {word}".strip()
        if current and font.getlength(candidate) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    return [*lines, current] if current else lines


def burn(image_bytes: bytes, extra: tuple[str, str] | None = None) -> bytes:
    """A JPEG of the concept with a dark band and both notices at the bottom; refuses anything that isn't an image.

    ``extra`` is one more notice as (Portuguese, English), each appended to its language's line."""
    with Image.open(io.BytesIO(image_bytes)) as source:
        if source.width * source.height > 40_000_000:
            raise ValueError("image too large")
        image = source.convert("RGB")
    image.thumbnail((MAX_SIDE, MAX_SIDE))
    w, h = image.size
    size = max(12, w // 60)
    font = ImageFont.truetype(FONT, size)  # missing font: OSError, and no concept is shown without its notice
    pt, en = (f"{NOTICE_PT}. {extra[0]}", f"{NOTICE_EN}. {extra[1]}") if extra else (NOTICE_PT, NOTICE_EN)
    lines = [(line, (255, 255, 255)) for line in _wrap(pt, font, w - 20)]
    lines += [(line, (220, 220, 220)) for line in _wrap(en, font, w - 20)]
    step = size + 6
    canvas = Image.new("RGB", (w, h + step * len(lines) + 12), (20, 24, 22))
    canvas.paste(image, (0, 0))
    draw = ImageDraw.Draw(canvas)
    for n, (line, colour) in enumerate(lines):
        draw.text((10, h + 6 + n * step), line, fill=colour, font=font)
    out = io.BytesIO()
    canvas.save(out, "JPEG", quality=88)
    return out.getvalue()
