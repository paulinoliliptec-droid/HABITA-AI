"""HR-012 in words, for the PDFs and the voice: what each concept is and is not (AC12.10)."""

from app.schemas.report import PermitReport
from app.services.concepts.label import NOTICE_EN
from app.services.i18n.translator import msg, translator_for

TITLE = msg("Before / after concepts")
NOT = msg("Each concept is an illustration generated by AI from your photo or plan. It is not a project, not an "
          "authorisation and not a promise of cost, and it changes nothing in the assessment.")
_FROM = {"photo": msg("{change}, from your photo, made on {date}."),
         "plan": msg("{change}, from your plan, made on {date}.")}


def rows(report: PermitReport) -> list[tuple[str, str]]:
    t = translator_for(report.language)
    out = [(t("Concept"), t(_FROM[c.source], change=c.change_label, date=c.created_on.isoformat()))
           for c in report.concepts]
    return [*out, ("", t(NOT)), ("", t(NOTICE_EN))] if out else []


def sentences(report: PermitReport) -> list[str]:
    t = translator_for(report.language)
    found = rows(report)
    return [t(TITLE), *[f"{a}: {b}" if a else b for a, b in found]] if found else []
